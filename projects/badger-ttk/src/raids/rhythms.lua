-- Key aliasing: the live client is expected to fire the classic DungeonEncounterID in ENCOUNTER_START,
-- while Warcraft Logs' Fresh partition names the same encounters at +150000 (the ids the lab's fixtures
-- carry). Alias both so either reality resolves; the in-game /reload confirms which.
local rhythms = {}
for id, prof in pairs(profiles) do
    rhythms[id] = prof
    rhythms[id + 150000] = prof
end

ns.Rhythms = rhythms
